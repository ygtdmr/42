char	*ft_strrchr(const char *s, int c)
{
	char	*ls;

	ls = 0;
	if (c > 255)
		return ((char *)s);
	while (*s)
	{
		if (*s == c)
			ls = ((char *)s);
		s++;
	}
	if (c == '\0')
		return ((char *)s);
	return (ls);
}
