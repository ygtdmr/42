int	ft_ispfe(const char *s)
{
	char	c;

	if (*s == 37)
		s++;
	c = *s;
	while ((c >= 48 && c <= 57) || c == '.' || c == '-')
		c = *++s;
	return (c == 'd' || c == 'f');
}
