#include "ft_printf.h"

int	ft_ispf(const char *s)
{
	char	c;

	c = *s;
	if (c == 37)
		s++;
	else
		return (0);
	return (
		c == 'd' || c == 'i' || c == 'u' || c == 'f' || \
		c == 'e' || c == 'E' || c == 'g' || c == 'G' || \
		c == 'c' || c == 'c' || c == 'p' || c == 'n' || \
		c == 'x' || c == 'X' || c == 'o' || c == '%'
	);
}
