#include "libftprintf.h"

size_t	ft_putint(int n)
{
	int		d;
	int		l;

	l = 0;
	if (n == -2147483648)
		return (ft_putstr("-2147483648"));
	if (n < 0)
	{
		l += ft_putchr(45);
		n *= -1;
	}
	if (n >= 10)
		l += ft_putint(n / 10);
	d = 48 + (n % 10);
	return (l + ft_putchr(d));
}
